const ESCAPES = Object.freeze({
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
});

/**
 * Escapa un valor para insertarlo como texto en HTML.
 * Preferí siempre textContent / createElement; esto existe para los casos en que
 * se arma una cadena HTML (por ejemplo, un template) con datos externos.
 * @param {unknown} value
 * @returns {string}
 */
export function escapeHtml(value) {
  if (value === null || value === undefined) return '';
  return String(value).replace(/[&<>"']/g, (char) => ESCAPES[char]);
}
